          b.taxCollected.toStringAsFixed(2),
          b.gross.toStringAsFixed(2),
        ],
      [
        'Total',
        tTaxable.toStringAsFixed(2),
        tTax.toStringAsFixed(2),
        tGross.toStringAsFixed(2),
      ],
    ]);
  }

