  static String exportAgedReceivablesCsv(List<AgedReceivable> list) {
    final total = list.fold<double>(0, (a, r) => a + r.outstanding);
    return buildQuotedCsv([
      ['Invoice ID', 'Customer', 'Outstanding', 'Days Overdue'],
      for (final r in list)
