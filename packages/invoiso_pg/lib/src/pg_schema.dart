import 'package:invoiso_core/database/database_helper.dart';
import 'package:postgres/postgres.dart' as pg;
import 'package:sqflite_common_ffi/sqflite_ffi.dart';

import 'pg_database.dart';
import 'sql_translate.dart';

/// One column as SQLite's `PRAGMA table_info` reports it.
class _Col {
  _Col(this.name, this.type, this.notNull, this.defaultSql, this.pk);

  final String name;
  final String type;
  final bool notNull;
  final String? defaultSql;
  final int pk;
}

class _Table {
  _Table(this.name, this.columns);

  final String name;
  final List<_Col> columns;

  List<String> get pk => (columns.where((c) => c.pk > 0).toList()
        ..sort((a, b) => a.pk.compareTo(b.pk)))
      .map((c) => c.name)
      .toList();

  /// SQLite `INTEGER PRIMARY KEY` columns are aliases of rowid.
  _Col? get integerPk {
    final pks = columns.where((c) => c.pk > 0).toList();
    return pks.length == 1 && pks.first.type.toUpperCase() == 'INTEGER'
        ? pks.first
        : null;
  }
}

/// The canonical schema, taken from a fresh SQLite database built by the
/// app's own `DatabaseHelper._createDB`, so Postgres never drifts from it.
///
/// Every Postgres table gets a `rowid` column (SQLite has one implicitly and
/// the services `ORDER BY rowid` to keep line-item order; inserts return it).
class SchemaSync {
  SchemaSync._(this._tables, this._indexSql, this._reference);

  final List<_Table> _tables;
  final List<String> _indexSql;

  /// Fresh SQLite DB with `_createDB` seed rows (admin user, defaults) — the
  /// source when a new company is created.
  final Database _reference;

  PgCatalog get catalog =>
      PgCatalog({for (final t in _tables) t.name: t.pk});

  static Future<SchemaSync> load() async {
    sqfliteFfiInit();
    final helper = DatabaseHelper();
    final ref = await databaseFactoryFfi.openDatabase(inMemoryDatabasePath,
        options: OpenDatabaseOptions(
            version: helper.dbVersion,
            onCreate: (db, _) => helper.createSchema(db)));
    final tables = <_Table>[];
    final names = await ref.rawQuery(
        "SELECT name FROM sqlite_master WHERE type = 'table' "
        "AND name NOT LIKE 'sqlite_%' AND name != 'android_metadata' ORDER BY name");
    for (final row in names) {
      final name = row['name'] as String;
      final info = await ref.rawQuery('PRAGMA table_info("$name")');
      tables.add(_Table(name, [
        for (final c in info)
          _Col(c['name'] as String, (c['type'] as String?) ?? '',
              c['notnull'] == 1, c['dflt_value'] as String?, c['pk'] as int),
      ]));
    }
    final idx = await ref.rawQuery(
        "SELECT sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL");
    return SchemaSync._(
        tables, [for (final r in idx) r['sql'] as String], ref);
  }

  static String schemaName(String companyId) =>
      'company_${companyId.replaceAll(RegExp(r'[^A-Za-z0-9_]'), '_')}';

  static String _pgType(String sqliteType) {
    final t = sqliteType.toUpperCase();
    if (t.contains('INT')) return 'bigint';
    if (t.contains('REAL') || t.contains('FLOA') || t.contains('DOUB') ||
        t.contains('NUM') || t.contains('DEC')) {
      return 'double precision';
    }
    if (t.contains('BLOB')) return 'bytea';
    return 'text';
  }

  static String? _pgDefault(String? sqliteDefault) {
    if (sqliteDefault == null) return null;
    final d = sqliteDefault.trim();
    if (d.toUpperCase() == 'CURRENT_TIMESTAMP') {
      return "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";
    }
    return d;
  }

  static String _columnDdl(_Col c, {required bool forAlter}) {
    final def = _pgDefault(c.defaultSql);
    final buf = StringBuffer('"${c.name}" ${_pgType(c.type)}');
    if (def != null) buf.write(' DEFAULT $def');
    // ADD COLUMN ... NOT NULL without a default fails on a non-empty table.
    if (c.notNull && (!forAlter || def != null)) buf.write(' NOT NULL');
    return buf.toString();
  }

  String _createTableDdl(_Table t) {
    final intPk = t.integerPk;
    final cols = <String>[
      for (final c in t.columns)
        if (c == intPk)
          '"${c.name}" bigint GENERATED BY DEFAULT AS IDENTITY'
        else
          _columnDdl(c, forAlter: false),
      intPk == null
          ? 'rowid bigserial'
          : 'rowid bigint GENERATED ALWAYS AS ("${intPk.name}") STORED',
    ];
    if (t.pk.isNotEmpty) {
      cols.add('PRIMARY KEY (${t.pk.map((c) => '"$c"').join(', ')})');
    }
    return 'CREATE TABLE IF NOT EXISTS "${t.name}" (\n  ${cols.join(',\n  ')}\n)';
  }

  String _indexDdl(String sqliteSql) {
    final pgSql = translateSql(sqliteSql);
    return pgSql.replaceFirstMapped(
        RegExp(r'^\s*CREATE\s+(UNIQUE\s+)?INDEX\s+(IF\s+NOT\s+EXISTS\s+)?',
            caseSensitive: false),
        (m) => 'CREATE ${m[1] ?? ''}INDEX IF NOT EXISTS ');
  }

  /// Shared helpers every company schema relies on (lives in `public`).
  static Future<void> ensureGlobals(pg.Session s) async {
    await s.execute(r'''
      CREATE OR REPLACE FUNCTION public.safe_int(t text) RETURNS bigint
      LANGUAGE sql IMMUTABLE AS $$
        SELECT CASE WHEN t IS NULL THEN NULL
          ELSE COALESCE(substring(t from '^\s*([-+]?[0-9]+)')::bigint, 0) END
      $$''');
  }

  /// Creates [schema] if needed and adds any missing tables, columns and
  /// indexes. Additive only — it never drops or alters existing columns.
  Future<void> sync(pg.Session s, String schema) async {
    await ensureGlobals(s);
    await s.execute('CREATE SCHEMA IF NOT EXISTS "$schema"');
    final existing = <String, Set<String>>{};
    final rows = await s.execute(
        r'SELECT table_name, column_name FROM information_schema.columns '
        r'WHERE table_schema = $1',
        parameters: [schema]);
    for (final r in rows) {
      existing.putIfAbsent(r[0] as String, () => {}).add(r[1] as String);
    }
    await s.execute('SET search_path TO "$schema", public');
    for (final t in _tables) {
      final have = existing[t.name];
      if (have == null) {
        await s.execute(_createTableDdl(t));
        continue;
      }
      for (final c in t.columns) {
        if (!have.contains(c.name)) {
          await s.execute(
              'ALTER TABLE "${t.name}" ADD COLUMN ${_columnDdl(c, forAlter: true)}');
        }
      }
    }
    for (final sql in _indexSql) {
      await s.execute(_indexDdl(sql));
    }
  }

  /// Copies every canonical table from [source] (an invoiso SQLite database,
  /// already upgraded to the current version) into [schema], which must be
  /// freshly synced and empty. Returns row counts per table.
  Future<Map<String, int>> copyFromSqlite(
      Database source, pg.Session s, String schema) async {
    await s.execute('SET search_path TO "$schema", public');
    final sourceTables = {
      for (final r in await source.rawQuery(
          "SELECT name FROM sqlite_master WHERE type = 'table'"))
        r['name'] as String,
    };
    final counts = <String, int>{};
    for (final t in _tables) {
      if (!sourceTables.contains(t.name)) continue;
      final srcCols = {
        for (final c in await source.rawQuery('PRAGMA table_info("${t.name}")'))
          c['name'] as String,
      };
      final cols = [for (final c in t.columns) if (srcCols.contains(c.name)) c.name];
      final withRowid = t.integerPk == null;
      final rows = await source.rawQuery(
          'SELECT ${withRowid ? 'rowid AS __rowid, ' : ''}'
          '${cols.map((c) => '"$c"').join(', ')} FROM "${t.name}" ORDER BY rowid');
      final insertCols = [if (withRowid) 'rowid', ...cols.map((c) => '"$c"')];
      for (var i = 0; i < rows.length; i += 200) {
        final chunk = rows.sublist(i, i + 200 > rows.length ? rows.length : i + 200);
        final params = <Object?>[];
        final tuples = <String>[];
        for (final row in chunk) {
          final vals = [if (withRowid) row['__rowid'], ...cols.map((c) => row[c])];
          tuples.add(
              '(${List.generate(vals.length, (k) => '\$${params.length + k + 1}').join(', ')})');
          params.addAll(vals.map((v) => v is List<int>
              ? pg.TypedValue(pg.Type.byteArray, v)
              : v));
        }
        await s.execute(
            'INSERT INTO "${t.name}" (${insertCols.join(', ')}) VALUES ${tuples.join(', ')}',
            parameters: params);
      }
      final seqCol = t.integerPk?.name ?? 'rowid';
      await s.execute(
          "SELECT setval(pg_get_serial_sequence('\"$schema\".\"${t.name}\"', '$seqCol'), "
          'COALESCE((SELECT MAX("$seqCol") FROM "${t.name}"), 0) + 1, false)');
      counts[t.name] = rows.length;
    }
    return counts;
  }

  /// New company: schema + tables + the same seed rows a fresh desktop
  /// install gets (default admin user, settings defaults, company stub).
  Future<void> createCompany(pg.Session s, String schema) async {
    await sync(s, schema);
    await copyFromSqlite(_reference, s, schema);
  }

  /// Opens an uploaded invoiso `.db` file and runs the app's own migration
  /// ladder so it matches the canonical schema before [copyFromSqlite].
  static Future<Database> openUpgradedSqlite(String path) {
    sqfliteFfiInit();
    final helper = DatabaseHelper();
    return databaseFactoryFfi.openDatabase(path,
        options: OpenDatabaseOptions(
            version: helper.dbVersion,
            onUpgrade: (db, oldV, newV) =>
                helper.upgradeSchema(db, oldV, newV)));
  }
}
